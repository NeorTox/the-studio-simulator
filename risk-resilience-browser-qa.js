const {chromium}=require('playwright'),assert=require('assert');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:844,height:390}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/index.html',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:/New campaign/}).click();
 await page.getByRole('button',{name:/Create campaign/}).click();
 for(const [id,value] of [['nfounder','Risk QA Founder'],['ncompany','Resilience Studios'],['ncountry','India'],['ncity','Kochi'],['ncapital','1000000']])await page.locator('#'+id).fill(value);
 await page.getByRole('button',{name:/Create and save campaign/}).click();
 await page.locator('[data-page="legal"]').click();
 assert.equal(await page.locator('#risk-resilience-panel').count(),1,'Risk dashboard mounts on Legal & Compliance');
 const before=await page.evaluate(()=>({cash:active.company.cash,posture:StudioRiskResilience.metrics().posture}));
 await page.locator('[data-risk-invest="identity"]').click();
 const after=await page.evaluate(()=>({cash:active.company.cash,posture:StudioRiskResilience.metrics().posture}));
 assert(Number(after.cash)<Number(before.cash),'Security investment posts to company cash ledger');
 assert(after.posture>before.posture,'Security investment improves control posture');
 await page.evaluate(()=>active.company.insurancePolicies.push({id:'CYBER-QA',name:'Cyber response policy',type:'Cybersecurity',coverage:500000,premium:500,deductible:100,startDate:active.date,endDate:'2027-12-31',status:'Active'}));
 const incident=await page.evaluate(()=>StudioRiskResilience.createIncident({id:'BROWSER-RISK-1',type:'ransomware',severity:70,date:active.date}).incident.id);
 await page.locator('[data-risk-action="contain"][data-risk-id="'+incident+'"]').click();
 assert.equal(await page.evaluate(id=>active.riskResilience.incidents.find(x=>x.id===id).status,incident),'contained','Containment action changes incident state');
 await page.locator('[data-risk-action="notify"][data-risk-id="'+incident+'"]').click();
 assert.equal(await page.evaluate(id=>active.riskResilience.incidents.find(x=>x.id===id).notified,incident),true,'Notification action is recorded');
 await page.locator('[data-risk-action="restore"][data-risk-id="'+incident+'"]').click();
 const result=await page.evaluate(id=>({incident:active.riskResilience.incidents.find(x=>x.id===id),audit:StudioRiskResilience.audit(),cash:active.company.cash,events:active.events.length}),incident);
 assert.equal(result.incident.status,'resolved','Restore action resolves the incident');
 assert(result.incident.insuranceRecovery>0,'Eligible cybersecurity policy pays an insurance recovery');
 assert.equal(result.audit.failed,0,'Risk integrity audit passes');
 assert(result.events>0,'Risk event is published into the shared event feed');
 await page.reload({waitUntil:'networkidle'});
 await page.locator('[data-page="legal"]').click();
 const saved=await page.evaluate(id=>({incident:active.riskResilience.incidents.find(x=>x.id===id)?.status,control:active.riskResilience.controls.identity}),incident);
 assert.equal(saved.incident,'resolved','Risk incident survives save and reload');
 assert(saved.control>30,'Security controls survive save and reload');
 assert.deepEqual(errors,[],'No browser page errors');
 await browser.close();
 console.log('Corporate risk resilience browser QA passed: dashboard, ledger-backed security investment, incident containment, notification, recovery, insurance claim, event publication and save/reload.');
})().catch(e=>{console.error(e);process.exit(1)});
