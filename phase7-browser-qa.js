const assert=require('assert');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/index.html',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:/New campaign/}).click();
 await page.getByRole('button',{name:/Create campaign/}).click();
 for(const [id,value] of [['nfounder','Phase Seven QA Founder'],['ncompany','Phase Seven QA Studios'],['ncountry','India'],['ncity','Mumbai']])await page.locator('#'+id).fill(value);
 await page.getByRole('button',{name:/Create and save campaign/}).click();
 const setup=await page.evaluate(()=>{
  const p=window.Phase7Smartphone;if(!p)throw Error('Phase 7 engine did not load');
  const s=p.ensure();const creator=p.createCreator({name:'QA Creator',handle:'qa_creator',category:'Film'});
  const app=s.platforms.find(x=>x.id==='playgrid');p.installApp(app.id);
  const post=p.publishPost({creatorId:creator.id,platformId:'studiosphere',text:'Testing the new entertainment social feed.'});
  const ad=p.createAdCampaign({name:'QA launch campaign',budget:10000,days:30});
  const first=p.processDay(active.date),second=p.processDay(active.date);
  return {creator,post,ad,first,second,audit:p.audit(),date:active.date};
 });
 assert.equal(setup.audit.failed,0,JSON.stringify(setup.audit.tests.filter(x=>!x.ok)));
 assert.equal(setup.second.processed,false,'Daily processing must be idempotent');
 assert(setup.first.generated>=1);
 assert.equal(setup.post.status,'Published');
 await page.evaluate(()=>window.advance(10));
 const result=await page.evaluate(()=>({date:active.date,state:active.smartphone,integrity:window.StudioPhaseIntegration.audit()}));
 assert.equal(result.state.lastProcessedDate,result.date);
 assert(result.state.feed.length>=10);
 assert(result.state.metrics.activeUsers>0);
 assert(result.state.trends.length>0);
 assert.equal(result.integrity.modules.find(x=>x.id===7).status,'connected');
 assert.equal(result.integrity.failed,0,JSON.stringify(result.integrity.tests.filter(x=>!x.ok)));
 assert.deepEqual(errors,[]);
 await page.reload({waitUntil:'networkidle'});
 const restored=await page.evaluate(()=>({date:active.date,state:active.smartphone,audit:window.Phase7Smartphone.audit()}));
 assert.equal(restored.state.lastProcessedDate,restored.date);
 assert.equal(restored.audit.failed,0,JSON.stringify(restored.audit.tests.filter(x=>!x.ok)));
 await page.getByRole('button',{name:/Phone/}).click();
 await page.getByText('Your smartphone').waitFor();
 await browser.close();
 console.log('PASS Phase 7 mobile smartphone, apps, creator publishing, personalized feed, ads, daily idempotency, integration, save/reload',JSON.stringify({setup:{apps:setup.audit.passed,creator:setup.creator.handle,post:setup.post.id,ad:setup.ad.id},final:{date:restored.date,feed:restored.state.feed.length,users:restored.state.metrics.activeUsers,trends:restored.state.trends.length,audit:restored.audit.passed}}));
})();