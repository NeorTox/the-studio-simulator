const fs=require('fs'),vm=require('vm'),assert=require('assert');
const nodes={};
function node(id){return nodes[id]||(nodes[id]={id,innerHTML:'',textContent:'',style:{},classList:{add(){},remove(){}},appendChild(el){if(el.innerHTML){for(const m of el.innerHTML.matchAll(/id="([^"]+)"/g))node(m[1]);} },setAttribute(){}})}
const document={readyState:'complete',getElementById:node,createElement:()=>({id:'',innerHTML:'',appendChild(){}}),addEventListener(){}};
let persisted=0,notices=[];
const active={date:'2026-11-14',founder:{name:'Founder',age:35,personalCash:1000,personalAssets:[],relationships:[],personalDebt:100,stress:20,skills:{stressManagement:50}},company:{currency:'INR'},projects:[],employees:[],worldSeed:'seed'};
const ctx={document,window:{},active,persist(){persisted++},toast:x=>notices.push(x),show(){},close(){},fmt:v=>'₹'+v,addLog(){},console,Date,Math};
vm.createContext(ctx);vm.runInContext(fs.readFileSync('phase3-founder-engine.js','utf8'),ctx);
assert(ctx.window.Phase3Founder,'public API initialized');
assert(nodes['phase3-personal'],'founder panel rendered');
assert(nodes['p3finance'].innerHTML.includes('1000'),'personal cash shown');
ctx.window.Phase3Founder.record('Income',250,'Salary','Test income');
