'use strict';
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1365,height:850}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/index.html',{waitUntil:'networkidle'});
 await page.waitForTimeout(1200);
 assert.equal(await page.title(),'THE STUDIO — v4.26.0');
 assert.equal(await page.locator('#studio-help-button').count(),1,'Help button must be available');
 assert.equal(await page.locator('#studio-tutorial-overlay').count(),0,'Automated browser runs should not be blocked by auto-onboarding');
 await page.locator('#studio-help-button').click();
 assert.equal(await page.locator('#studio-tutorial-overlay').count(),1,'Tutorial should be available from Help');
 await page.locator('#studio-tour-skip').click();
 await page.locator('[data-page="situations"]').click();
 assert.equal(await page.locator('#page-situations').evaluate(e=>e.classList.contains('active')),true);
 assert.equal(await page.locator('#studio-situation-feed').count(),1);
 await page.locator('[data-page="worldengine"]').click();
 assert.equal(await page.locator('#page-worldengine').evaluate(e=>e.classList.contains('active')),true);
 assert.equal(await page.locator('#studio-world-risk').count(),1);
 await page.locator('#studio-help-button').click();
 assert.equal(await page.locator('#studio-tutorial-dialog').count(),1);
 await page.locator('#studio-tour-skip').click();
 await page.waitForTimeout(150);
 assert.deepEqual(errors,[],'No uncaught page errors: '+errors.join('; '));
 const metrics=await page.evaluate(()=>({layout:getComputedStyle(document.querySelector('.shell')).gridTemplateColumns,css:!![...document.styleSheets].some(s=>s.href&&s.href.includes('studio-overhaul.css')),risk:!!window.StudioWorldRisk,tutorial:!!window.StudioTutorial}));
 assert.equal(metrics.css,true);assert.equal(metrics.risk,true);assert.equal(metrics.tutorial,true);
 const engines=await page.evaluate(()=>({responses:window.StudioNPCDecisionConsequences?.responseStyles?.length,templates:window.StudioNPCDecisionConsequences?.catalog?.length,riskAudit:window.StudioWorldRisk?.audit?.().failed}));
 assert.equal(engines.responses,12);assert.equal(engines.templates,100);assert.equal(engines.riskAudit,0);
 console.log('PLAYER EXPERIENCE BROWSER QA PASSED',JSON.stringify(metrics));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
